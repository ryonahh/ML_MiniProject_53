"""Extract the World Bank indicators used by the project from the WDI bulk download.

The full World Development Indicators CSV is about 200 MB, so it is not stored in
git. This script keeps the six indicators used by the reference paper, for real
countries only, and writes them to ``data/external/world_bank_indicators.csv``
(about 1 MB) keyed by the country names used in the Olympic data.

Usage:
    python scripts/prepare_world_bank.py --wdi path/to/WDICSV.csv --countries path/to/WDICountry.csv

Download: https://datacatalog.worldbank.org/search/dataset/0037712 (CSV bulk download).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from olympic_momentum.config import WORLD_BANK_CSV  # noqa: E402
from olympic_momentum.economic import WDI_INDICATORS, olympic_to_iso3  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--wdi", required=True, type=Path, help="WDICSV.csv from the bulk download")
    parser.add_argument("--countries", required=True, type=Path, help="WDICountry.csv from the bulk download")
    parser.add_argument("--olympic", type=Path, default=None, help="optional processed Olympic table for name matching")
    args = parser.parse_args()

    countries = pd.read_csv(args.countries, encoding="utf-8-sig")
    countries = countries[countries["Region"].notna()]  # drop aggregates such as "World"

    wdi = pd.read_csv(args.wdi, encoding="utf-8-sig")
    wdi = wdi[wdi["Indicator Code"].isin(WDI_INDICATORS) & wdi["Country Code"].isin(countries["Country Code"])]
    year_columns = [c for c in wdi.columns if c.isdigit()]
    long = wdi.melt(id_vars=["Country Code", "Indicator Code"], value_vars=year_columns,
                    var_name="Year", value_name="value").dropna(subset=["value"])
    long["Year"] = long["Year"].astype(int)
    long["Indicator"] = long["Indicator Code"].map(WDI_INDICATORS)
    table = long.pivot_table(index=["Country Code", "Year"], columns="Indicator", values="value").reset_index()

    iso_to_country = {iso: name for name, iso in olympic_to_iso3(countries).items()}
    table.insert(0, "Country", table["Country Code"].map(iso_to_country))
    table = table.dropna(subset=["Country"]).rename(columns={"Country Code": "ISO3"})
    table = table.sort_values(["Country", "Year"])

    WORLD_BANK_CSV.parent.mkdir(parents=True, exist_ok=True)
    header = ("# World Bank World Development Indicators (bulk CSV), six series used by the reference paper.\n"
              "# Generated by scripts/prepare_world_bank.py. Country names follow noc_regions.csv.\n")
    WORLD_BANK_CSV.write_text(header + table.to_csv(index=False, float_format="%.6g"))
    print(f"Wrote {len(table):,} rows for {table['Country'].nunique()} countries to {WORLD_BANK_CSV}")


if __name__ == "__main__":
    main()
